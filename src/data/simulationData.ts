/**
 * Fisher-Yates shuffle array algorithm
 */
function shuffleArray<T>(array: T[]): T[] {
  const arr = [...array];
  for (let i = arr.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [arr[i], arr[j]] = [arr[j], arr[i]];
  }
  return arr;
}

/**
 * Generates an expanded, cheat-proof simulation test:
 * - Selects 15 rich, deep scenario questions (5 Organizational, 5 Behavioral/Leadership, 5 Legal)
 * - Shuffles the question order so they appear mixed and unpredictable
 * - Shuffles the 4 options inside every question so memorizing positions is impossible
 * - Issues a unique certificate tracking session code (SNTE-CERT-2026-XXXX)
 */
export function generateExpandedSimulation(
  questionsPerCategory = 5
): { questions: SimulationQuestion[]; sessionCode: string } {
  const orgQuestions = COMPREHENSIVE_QUESTION_BANK.filter((q) => q.category === 'تنظيمي ومؤسساتي');
  const behQuestions = COMPREHENSIVE_QUESTION_BANK.filter((q) => q.category === 'سلوكي وقيادي وتفاوضي');
  const legQuestions = COMPREHENSIVE_QUESTION_BANK.filter((q) => q.category === 'قانوني وتشريعي');

  const selectedOrg = shuffleArray(orgQuestions).slice(0, questionsPerCategory);
  const selectedBeh = shuffleArray(behQuestions).slice(0, questionsPerCategory);
  const selectedLeg = shuffleArray(legQuestions).slice(0, questionsPerCategory);

  // Combine and shuffle the entire question list so categories appear mixed
  const combined = shuffleArray([...selectedOrg, ...selectedBeh, ...selectedLeg]);

  // Deep clone and shuffle options for every question
  const randomizedQuestions: SimulationQuestion[] = combined.map((q) => ({
    ...q,
    options: shuffleArray(q.options)
  }));

  // Unique session & certificate code
  const randomSuffix = Math.random().toString(36).substring(2, 7).toUpperCase();
  const sessionCode = `SNTE-CERT-2026-${randomSuffix}`;

  return {
    questions: randomizedQuestions,
    sessionCode
  };
}

